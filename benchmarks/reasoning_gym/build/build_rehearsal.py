"""Build Reasoning Gym t2 rehearsal datasets.

Input: t2 rehearsal traces from tasks generated by `gen_rehearsal.py`, plus
`miniswe-only` and `goose-only` from `build_pools.py`.

Writes:
- `miniswe+goose`: cross-task control.
- `miniswe+goose+reh-t2`: control plus rehearsal rows.
- `reh-t2`: up to 120 solved rehearsal trajectories.

With `--demonstrator 32b`, reads the `rehearsal-t2~32b` job (the Qwen3-32B teacher on the
same rehearsal tasks) and writes only `reh-t2~32b`, capped like `reh-t2`: the clean-demonstrator
control's rows.

With `--failed-only`, writes only `reh-t2~fail`: up to 120 rehearsal trajectories that
did not pass the verifier (at most two per task), the failed-rehearsal control's rows. The
shipped `reh-t2` and `miniswe+goose+reh-t2` are left untouched, so the control can be built
from a later collection of the same demonstrator on the same tasks.
"""
import random
import sys
from glob import glob
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402

CAP = 120  # the size of t2-only


def solved(job_dir, failed=False, source=None):
    """Rehearsal trajectories with reward 1 (or, with `failed`, below 1: scored and not solved),
    at most two per task, in listing order (as run). `source` overrides the rows' source tag."""
    rows, per_task = [], {}
    for t in glob(f"{job_dir}/*/"):
        try:
            reward = float(open(f"{t}/verifier/reward.txt").read().strip())
        except (OSError, ValueError):
            continue
        if (reward < 0.999) != failed:
            continue
        task = C.task_of(t)
        if per_task.get(task, 0) >= C.PER_TASK:
            continue
        msgs = C.chat_t2(t.rstrip("/"))
        if not msgs:
            continue
        rows.append({"messages": msgs, "meta": {"task": C.task_name(t), "harness": "t2",
                                                "source": source or ("rehearsal~fail" if failed else "rehearsal"),
                                                "reward": 0.0 if failed else 1.0}})
        per_task[task] = per_task.get(task, 0) + 1
    return rows


def main():
    p = C.parser(__doc__, {"rehearsal": "rehearsal-t2", "rehearsal_32b": "rehearsal-t2~32b"})
    p.add_argument("--failed-only", action="store_true", help="write only reh-t2~fail (failed rehearsal trajectories)")
    p.add_argument("--demonstrator", choices=["student", "32b"], default="student",
                   help="32b: write only reh-t2~32b from the Qwen3-32B teacher's rehearsal job")
    args = p.parse_args()
    if args.demonstrator == "32b":
        jobs = C.job_dirs(args, {"rehearsal_32b": "rehearsal-t2~32b"})
        rows = solved(jobs["rehearsal_32b"], source="rehearsal~32b")
        rate = C.think_rate(rows)
        print(f"rehearsal (32B): {len(rows)} rows from {jobs['rehearsal_32b']} (think rate {rate:.2f})")
        if len(rows) < 40 or rate < 0.9:
            raise SystemExit("fewer than 40 rehearsal rows or think rate below 0.9; check the traces")
        rows_ = C.capped(random.Random(0), rows, CAP)
        random.Random(0).shuffle(rows_)
        C.write_pool(args.out_dir, "reh-t2~32b", rows_)
        return
    jobs = C.job_dirs(args, {"rehearsal": "rehearsal-t2"})
    if args.failed_only:
        failed = solved(jobs["rehearsal"], failed=True)
        print(f"failed rehearsal: {len(failed)} rows from {jobs['rehearsal']} (think rate {C.think_rate(failed):.2f})")
        if len(failed) < 40:
            raise SystemExit("fewer than 40 failed rehearsal rows; check the traces")
        rows_ = C.capped(random.Random(0), failed, CAP)
        random.Random(0).shuffle(rows_)
        C.write_pool(args.out_dir, "reh-t2~fail", rows_)
        return
    rows = solved(jobs["rehearsal"])
    rate = C.think_rate(rows)
    print(f"rehearsal: {len(rows)} rows from {jobs['rehearsal']} (think rate {rate:.2f})")
    if len(rows) < 40 or rate < 0.9:
        raise SystemExit("fewer than 40 rehearsal rows or think rate below 0.9; check the traces")

    rng = random.Random(0)
    rehearsal = C.capped(rng, rows, CAP)
    cross = C.read_pool(args.out_dir, "miniswe-only") + C.read_pool(args.out_dir, "goose-only")
    for name, rows_ in [("miniswe+goose", cross), ("miniswe+goose+reh-t2", cross + rehearsal), ("reh-t2", rehearsal)]:
        rows_ = rows_[:]
        rng.shuffle(rows_)
        C.write_pool(args.out_dir, name, rows_)


if __name__ == "__main__":
    main()
